/**
 * تولید sitemap.xml و robots.txt برای بیلد تولیدی.
 *
 * دامنهٔ نهایی را با متغیر محیطی SITE_URL مشخص کنید؛ در نبود آن، دامنهٔ
 * پیش‌فرض زیر استفاده می‌شود. اگر سامانه روی Vercel/Netlify مستقر شود،
 * متغیرهای URL آن‌ها هم به‌صورت خودکار بررسی می‌شوند.
 *
 * مثال (PowerShell):  $env:SITE_URL="https://my-domain.com"; npm run build
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dist = resolve(root, "dist");

function resolveSiteUrl() {
  const candidates = [
    process.env.SITE_URL,
    process.env.URL,
    process.env.VERCEL_PROJECT_PRODUCTION_URL
      ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`
      : "",
    process.env.VERCEL_URL ? `https://${process.env.VERCEL_URL}` : "",
  ];
  const found = candidates.find((value) => value && value.trim());
  return (found || "https://hozorban.ir").trim().replace(/\/+$/, "");
}

const siteUrl = resolveSiteUrl();
const lastmod = new Date().toISOString().slice(0, 10);

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
  <url>
    <loc>${siteUrl}/</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>weekly</changefreq>
    <priority>1.0</priority>
    <xhtml:link rel="alternate" hreflang="fa-IR" href="${siteUrl}/" />
    <xhtml:link rel="alternate" hreflang="en" href="${siteUrl}/" />
    <xhtml:link rel="alternate" hreflang="x-default" href="${siteUrl}/" />
  </url>
</urlset>
`;

const robots = `# robots.txt generated by scripts/build-seo.mjs
User-agent: *
Allow: /
Disallow: /api/
Disallow: /uploads/
Disallow: /offline.html

Sitemap: ${siteUrl}/sitemap.xml
`;

mkdirSync(dist, { recursive: true });
writeFileSync(resolve(dist, "sitemap.xml"), sitemap, "utf8");
writeFileSync(resolve(dist, "robots.txt"), robots, "utf8");

console.log(`SEO files written for ${siteUrl}`);
