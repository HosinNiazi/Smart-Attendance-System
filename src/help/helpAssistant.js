const DIGIT_MAP = {
  "۰": "0", "۱": "1", "۲": "2", "۳": "3", "۴": "4",
  "۵": "5", "۶": "6", "۷": "7", "۸": "8", "۹": "9",
  "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
  "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
};

const STOP_WORDS = new Set([
  "از", "به", "با", "در", "و", "یا", "که", "این", "آن", "برای", "تا", "را",
  "چه", "چی", "چطور", "چگونه", "چجوری", "آیا", "می", "شود", "شده", "کنم",
  "کنید", "کنیم", "هست", "است", "بود", "من", "ما", "شما", "آنها", "روی",
  "یک", "هم", "همان", "دارد", "دارم", "دارید", "خود", "اگر", "ولی", "اما",
  "کجا", "کی", "کدام", "چند", "کند", "کرد", "کردن", "باید", "نباید",
]);

export function normalizeText(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[يى]/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/[۰-۹٠-٩]/g, (d) => DIGIT_MAP[d] || d)
    .replace(/[\u200c\u200e\u200f]/g, " ")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function tokenize(value) {
  return normalizeText(value)
    .split(" ")
    .filter((token) => token.length > 2 && !STOP_WORDS.has(token));
}

function keywordWeight(keyword) {
  const words = normalizeText(keyword).split(" ").filter(Boolean);
  return 2.6 + words.length * 0.9;
}

function scoreTopic(topic, query, queryTokens) {
  let score = 0;

  for (const keyword of topic.keywords || []) {
    const normalized = normalizeText(keyword);
    if (!normalized) continue;

    if (query.includes(normalized)) {
      score += keywordWeight(keyword);
      if (query === normalized) score += 2;
      continue;
    }

    const keywordTokens = normalized.split(" ").filter(Boolean);
    let hits = 0;
    for (const token of keywordTokens) {
      if (token.length < 3) continue;
      if (queryTokens.includes(token)) hits += 1;
    }
    if (hits) {
      const ratio = hits / Math.max(keywordTokens.length, 1);
      score += hits * 0.75 + ratio * 0.75;
    }
  }

  // عنوان موضوع هم کمی وزن دارد تا پرسش‌های کوتاه بهتر تشخیص داده شوند.
  for (const token of tokenize(topic.title)) {
    if (queryTokens.includes(token)) score += 0.55;
  }

  return score;
}

function topicCard(id) {
  const topic = TOPICS.find((item) => item.id === id);
  return topic ? { id: topic.id, title: topic.title, icon: topic.icon } : null;
}

function uniqueSuggestions(ids) {
  const seen = new Set();
  return ids
    .map(topicCard)
    .filter((item) => item && !seen.has(item.id) && seen.add(item.id));
}

