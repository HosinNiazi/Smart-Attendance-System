const GREETINGS = [
  "سلام", "درود", "وقت بخیر", "روز بخیر", "شب بخیر", "hi", "hello",
];
const THANKS = ["ممنون", "مرسی", "سپاس", "تشکر", "دستت درد نکنه", "عالی بود"];
const CAPABILITIES = [
  "چه کارهایی", "چیکار", "چی کار", "کمک", "راهنما", "چه سوالی",
  "چطور میتونی", "توانایی", "امکانات",
];

function hasAny(query, list) {
  return list.some((item) => query.includes(normalizeText(item)));
}

function suggestionsFor(ids) {
  return uniqueSuggestions(ids.length ? ids : QUICK_TOPICS).slice(0, 4);
}

function fallbackAnswer(query, ranked) {
  const top = ranked.slice(0, 3).map((item) => item.topic);
  const suggestions = top.length ? suggestionsFor(top.map((item) => item.id)) : suggestionsFor([]);

  if (!query) {
    return {
      answer:
        "سؤال خود را بنویسید یا یکی از موضوع‌های پیشنهادی را انتخاب کنید. " +
        "می‌توانم دربارهٔ ورود، ثبت‌نام، دانشجویان، کلاس‌ها، جلسات، حضور دستی، تشخیص چهره و صدا، دوربین کلاس، گزارش‌ها و تنظیمات راهنمایی‌تان کنم.",
      suggestions,
    };
  }

  return {
    answer:
      "پاسخ دقیقی برای این عبارت در راهنمای سامانه پیدا نکردم.\n" +
      "می‌توانید کلمات کلیدی دیگری بنویسید؛ مثلاً «ثبت حضور دستی»، «تشخیص چهره»، «میکروفون» یا «تأیید ثبت‌نام». " +
      "اگر موضوع نزدیک به پرسش شما در فهرست زیر هست، انتخابش کنید:",
    suggestions,
  };
}

export function getAnswer(rawQuery) {
  const query = normalizeText(rawQuery);

  if (!query) return fallbackAnswer("", []);

  if (hasAny(query, GREETINGS) && query.split(" ").length <= 4) {
    return {
      answer:
        "سلام و وقت بخیر 👋\n" +
        "من دستیار راهنمای حضوربان هستم. دربارهٔ امکانات سامانه و روند کار بخش‌های مختلف پاسخ می‌دهم. " +
        "سؤال خود را بنویسید یا یکی از موضوع‌های پیشنهادی را انتخاب کنید.",
      suggestions: suggestionsFor(QUICK_TOPICS),
    };
  }

  if (hasAny(query, THANKS)) {
    return {
      answer:
        "خواهش می‌کنم 🌱 اگر سؤال دیگری دربارهٔ حضوربان دارید، همین‌جا بنویسید.",
      suggestions: suggestionsFor(QUICK_TOPICS),
    };
  }

  if (hasAny(query, CAPABILITIES)) {
    return {
      answer:
        "می‌توانم در این موضوع‌ها راهنمایی‌تان کنم:\n" +
        "• ورود، نقش‌ها و حساب‌های کاربری\n" +
        "• ثبت‌نام دانشجو و پذیرش درخواست توسط مدیر\n" +
        "• مدیریت دانشجویان، عکس پروفایل و عکس مرجع چهره\n" +
        "• درس‌ها، کلاس‌ها و جلسات\n" +
        "• ثبت دستی حضور، وضعیت غایب پیش‌فرض و بازهٔ زمانی\n" +
        "• تشخیص چهره، آزمون پلک و دوربین کلاس\n" +
        "• تشخیص صدا و رفع مشکل میکروفون\n" +
        "• گزارش‌ها، تنظیمات، دیتابیس و پشتیبان‌گیری\n\n" +
        "کافی است موضوع را بنویسید یا از پیشنهادها انتخاب کنید.",
      suggestions: suggestionsFor(QUICK_TOPICS),
    };
  }

  const queryTokens = tokenize(rawQuery);

  const ranked = TOPICS.map((topic) => ({
    topic,
    score: scoreTopic(topic, query, queryTokens),
  })).sort((a, b) => b.score - a.score);

  const best = ranked[0];

  if (!best || best.score < 2.4) {
    return fallbackAnswer(query, ranked);
  }

  const related = [best.topic.id, ...(best.topic.related || [])];
  return {
    answer: best.topic.answer,
    suggestions: suggestionsFor(related),
  };
}

export function getTopic(id) {
  return topicCard(id);
}

